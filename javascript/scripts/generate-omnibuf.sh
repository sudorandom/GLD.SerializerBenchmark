#!/usr/bin/env bash
# Generate static OmniBuf ESM codecs from schemas/v2/protobuf/benchmark_v2.proto.
# Uses @omnibuf/protoc-gen-omnibuf-es to emit TypeScript, then esbuild to strip types
# into plain ESM compatible with Node 18+.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$ROOT/.." && pwd)"
OUT="$ROOT/src/generated"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"

protoc \
  --plugin=protoc-gen-omnibuf-es="$ROOT/node_modules/.bin/protoc-gen-omnibuf-es" \
  --omnibuf-es_out="$TMP" \
  -I "$REPO/schemas/v2/protobuf" \
  "$REPO/schemas/v2/protobuf/benchmark_v2.proto"

"$ROOT/node_modules/.bin/esbuild" "$TMP/benchmark_v2_omnibuf.pb.ts" \
  --format=esm --platform=node --target=node18 \
  --legal-comments=none \
  --banner:js="// Generated by scripts/generate-omnibuf.sh from schemas/v2/protobuf/benchmark_v2.proto. Do not edit." \
  --outfile="$OUT/benchmark_v2_omnibuf.pb.js"

echo "[OK] wrote $OUT/benchmark_v2_omnibuf.pb.js"
